"""Builds dist/sacrapasta.ags from assets/ and src/.

    python3 tools/build.py --agscc ~/ags/Compiler/agscc --agsdefns ~/ags/Editor/AGS.Editor/Resources/agsdefns.sh

agscc is the AGS 3.6.1 command-line script compiler (Compiler/ in the AGS
sources); agsdefns.sh is the built-in script header that ships with the AGS
editor. Everything else (game data, rooms, sprites, the package) is written
by the Python code in tools/agsbuild.
"""
import argparse
import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
sys.path.insert(0, HERE)
from agsbuild import formats, gamedata as G, script as S

GAME_ID = 9130714          # rooms carry this; it must match the game's unique id
SCALING = {1: (60, 80), 2: (56, 67)}   # characters are drawn 150 px tall; the Crypt is drawn smaller


def c565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def cname(s):
    return ''.join(ch if ch.isalnum() else '_' for ch in s).upper()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--agscc', default=os.path.expanduser('~/ags/Compiler/agscc'))
    ap.add_argument('--agsdefns', default=os.path.expanduser('~/ags/Editor/AGS.Editor/Resources/agsdefns.sh'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'dist', 'sacrapasta.ags'))
    args = ap.parse_args()

    A = lambda rel: os.path.join(ROOT, 'assets', rel)
    with open(A('manifest.json')) as f:
        man = json.load(f)

    # ---- sprites: 0 is a blank, then the manifest order
    sprite_names = ['__blank'] + man['sprites']
    num = {n: i for i, n in enumerate(sprite_names)}
    sprites = [Image.new('RGBA', (1, 1), (0, 0, 0, 0))]
    for n in man['sprites']:
        sprites.append(Image.open(A('sprites/%s.png' % n)).convert('RGBA'))

    # ---- views
    views = []
    vnum = {}
    for v in man['views']:
        loops = [[G.Frame(num[f], delay, flip) for f, delay, flip in loop] for loop in v['loops']]
        views.append(G.View(v['name'], loops))
        vnum[v['name']] = len(views)

    # ---- characters
    chars = [
        G.Character('cGuest', 'yourself', vnum['VGUEST'], speech_view=vnum['VGTALK'], room=3, x=-100, y=300,
                    speech_color=c565(250, 250, 250), walk_x=4, walk_y=3, anim_delay=3, clickable=True),
        G.Character('cKhuc', 'Chuk', vnum['VKHUC'], speech_view=vnum['VKTALK'], room=1, x=540, y=262,
                    speech_color=c565(255, 176, 80), walk_x=3, walk_y=2, anim_delay=4),
        G.Character('cMini', 'yourself, back then', vnum['VMINI'], speech_view=vnum['VMINITALK'], room=-1, x=-50, y=-50,
                    speech_color=c565(200, 255, 200), walk_x=4, walk_y=3, anim_delay=3, clickable=False),
        G.Character('cVoice', 'voice', vnum['VBLANK'], room=-1, x=-50, y=-50,
                    speech_color=c565(250, 250, 250), clickable=False),
    ]

    cursor = num['cursor']
    names = ['Walkto', 'Lookat', 'Interact', 'Talkto', 'Useinv', 'Pickup', 'Pointer', 'Wait', 'Mode8', 'Mode9']
    cursors = [G.Cursor(n, cursor, 10, 10) for n in names]

    inventory = [G.InvItem(i['script'], i['name'], num[i['sprite']], cursor=num[i['sprite']], hotx=24, hoty=20)
                 for i in man['inventory']]

    fonts = []
    for fdesc in man['fonts']:
        with open(A(fdesc['file']), 'rb') as f:
            data = f.read()
        fonts.append(G.Font(data, outline=G.FONT_OUTLINE_AUTO if fdesc['outline'] == 'auto' else -1,
                            outline_thickness=1))

    audio = []
    audio_assets = []
    for k, a in enumerate(man['audio']):
        fname = 'au%04d.wav' % k
        with open(A(a['file']), 'rb') as f:
            data = f.read()
        audio.append(G.AudioClip(a['script'], fname, data, type=a['type'], file_type=3, repeat=a['repeat']))
        audio_assets.append((fname, data))

    game = G.Game('Hotel Paradiso: Sacra Pasta', 640, 400, 'Hotel Paradiso Sacra Pasta', fonts, sprites, cursors,
                  inventory, views, chars, 0, b'', b'', audio=audio,
                  guid='{6b7a3c51-913a-4f0e-8d1c-5ac7a9a50714}', unique_id=GAME_ID,
                  room_names={1: 'The Nave', 2: 'The Crypt', 3: 'Title', 4: 'HOTEL.EXE'})

    # ---- generated script headers
    things = ['// generated by tools/build.py -- room, hotspot, object and sprite numbers']
    for rn, room in sorted(man['rooms'].items(), key=lambda kv: int(kv[0])):
        rname = cname(room['name'])
        things.append('#define R_%s %s' % (rname, rn))
        for k, (script, _, _) in enumerate(room['hotspots']):
            things.append('#define H_%s_%s %d' % (rname, cname(script[1:]), k + 1))
        for k, o in enumerate(room['objects']):
            oname = cname(o['script'][1:])
            things.append('#define O_%s_%s %d' % (rname, oname, k))
            for state, sname in o['sprites'].items():
                things.append('#define S_%s_%s_%s %d' % (rname, oname, cname(state), num[sname]))
    things.append('#define SPR_PLATE %d' % num['plate'])
    things.append('#define SPR_HP_SCREEN %d' % num['hp_screen'])
    for k in range(6):
        things.append('#define SPR_HP_LOAD%d %d' % (k, num['hp_loading%d' % k]))
    things.append('#define SPR_CURSOR %d' % num['cursor'])
    things_h = '\n'.join(things) + '\n'

    with open(args.agsdefns) as f:
        agsdefns = f.read()
    with open(os.path.join(ROOT, 'src', 'game.ash')) as f:
        game_ash = f.read()
    with open(os.path.join(ROOT, 'src', 'game.asc')) as f:
        game_asc = f.read()
    headers = [('agsdefns.sh', agsdefns), ('_AutoGenerated.ash', G.auto_header(game)),
               ('_Things.ash', things_h), ('game.ash', game_ash)]
    work = os.path.join(ROOT, 'build')
    game.global_script = S.compile_script(args.agscc, game_asc, headers, 'GlobalScript.asc', work)
    game.dialog_script = S.compile_script(args.agscc, '', headers, '__DialogScripts.asc', work)

    assets = [('game28.dta', None), ('acsprset.spr', None)]
    room_assets = []
    for rn, room in sorted(man['rooms'].items(), key=lambda kv: int(kv[0])):
        bgs = [Image.open(A(p)).convert('RGBA') for p in room['bg']]
        walk = Image.open(A(room['walk'])).convert('L')
        hot = Image.open(A(room['hot'])).convert('L')
        wb = Image.open(A(room['wb'])).convert('L')
        r = formats.Room(int(rn), bgs, walk, hot, walkbehind=wb)
        r.game_id = GAME_ID
        for script, name, walkto in room['hotspots']:
            r.add_hotspot(script, name, tuple(walkto))
        for o in room['objects']:
            r.add_object(o['script'], o['name'], num[o['sprites'][o['state']]], o['x'], o['y'],
                         visible=o['visible'], baseline=o['baseline'], clickable=o['clickable'])
        r.walkbehind_baselines = room['wb_baselines']
        if int(rn) in SCALING:
            r.scaling = {1: SCALING[int(rn)]}
        room_header = ''.join('import Object %s;\n' % o['script'] for o in room['objects'])
        room_header += ''.join('import Hotspot %s;\n' % h[0] for h in room['hotspots'])
        r.script = S.compile_script(args.agscc, '// room %s\n' % room['name'],
                                    headers + [('_Room%s.ash' % rn, room_header)],
                                    'room%s.asc' % rn, work)
        room_assets.append(('room%s.crm' % rn, r.write()))

    assets = [('game28.dta', game.write()), ('acsprset.spr', formats.write_sprite_file(sprites))]
    assets += room_assets
    for k, f in enumerate(fonts):
        assets.append(('agsfnt%d.wfn' % k, f.data))
    assets += audio_assets
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    formats.write_clib(assets, args.out, os.path.basename(args.out))
    print('wrote %s (%d bytes, %d sprites, %d views, %d rooms)' % (
        args.out, os.path.getsize(args.out), len(sprites), len(views), len(room_assets)))


if __name__ == '__main__':
    main()
